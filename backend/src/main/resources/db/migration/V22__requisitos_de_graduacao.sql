-- Requisitos do próximo grau como checklist pessoal (#196, D78).
--
-- SQL portável (ANSI) pelo mesmo motivo da V1: as mesmas migrations rodam em Postgres e em H2 no
-- modo de compatibilidade PostgreSQL.
--
-- O texto vem DE FORA: é a lista que a academia de quem usa entregou, colada pela própria pessoa.
-- Material de academia costuma ser protegido, e o repositório é público — por isso a lista é dado
-- da conta, e nunca currículo (D11). Só a própria conta lê; `DELETE /api/me` leva tudo junto; a
-- coleta da D50 e o painel da D52 nunca leem estas tabelas.

-- Uma checklist por conta, como a meta da V20: o FOS acompanha o PRÓXIMO grau, não um histórico.
CREATE TABLE graduation_checklist (
    user_id    BIGINT      NOT NULL PRIMARY KEY REFERENCES app_user (id),
    -- Rótulo livre do grupo ("branca 2º grau"): cada academia nomeia do seu jeito.
    label      VARCHAR(60),
    updated_at TIMESTAMP   NOT NULL
);

CREATE TABLE graduation_requirement (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT       NOT NULL REFERENCES app_user (id),
    order_index INT          NOT NULL,
    text        VARCHAR(200) NOT NULL,
    -- Marcação à mão, e só vale para requisito SEM nó: o de nó tem status derivado do progresso.
    manual_done BOOLEAN      NOT NULL,
    created_at  TIMESTAMP    NOT NULL
);

CREATE INDEX ix_graduation_requirement_user ON graduation_requirement (user_id, order_index);

-- O vínculo guarda o CÓDIGO do nó, a chave estável do currículo (D11), e não o id: a ingestão
-- preserva ids, mas o código é o que a pessoa vê e o que o JSON garante. Quem confere que o código
-- existe é o serviço, na gravação.
CREATE TABLE graduation_requirement_node (
    requirement_id BIGINT      NOT NULL REFERENCES graduation_requirement (id),
    node_code      VARCHAR(16) NOT NULL,
    PRIMARY KEY (requirement_id, node_code)
);
