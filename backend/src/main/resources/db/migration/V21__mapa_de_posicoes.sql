-- Mapa de posições (#194, D76): as posições do jiu-jitsu como dado do currículo, e o vínculo de
-- cada nó com a posição de onde a técnica parte.
--
-- SQL portável (ANSI) pelo mesmo motivo da V1: as mesmas migrations rodam em Postgres e em H2 no
-- modo de compatibilidade PostgreSQL. `curriculum_position`, e não `position`: POSITION é palavra
-- reservada em SQL.
--
-- Tudo aqui é projeção de `curriculum/positions.json` e dos arquivos de módulo (D11), reescrita a
-- cada ingestão. Nenhum dado de usuário aponta para estas tabelas.

CREATE TABLE curriculum_position (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(40)  NOT NULL UNIQUE,
    name        VARCHAR(80)  NOT NULL,
    -- GUARDA | CONTROLE_POR_CIMA | COSTAS | TRANSICAO | EM_PE
    family      VARCHAR(24)  NOT NULL,
    -- BAIXO | CIMA | NEUTRA: de que lado o nome da posição é dito.
    perspective VARCHAR(8)   NOT NULL,
    -- Como reconhecer a posição, nunca como chegar nela (D1). A faixa de tamanho é do validador.
    identify    VARCHAR(400) NOT NULL,
    order_index INT          NOT NULL
);

CREATE TABLE curriculum_position_alias (
    position_id BIGINT      NOT NULL REFERENCES curriculum_position (id),
    alias_order INT         NOT NULL,
    alias       VARCHAR(60) NOT NULL,
    PRIMARY KEY (position_id, alias_order)
);

-- O nó guarda o CÓDIGO da posição, e não o id: a posição é reescrita a cada ingestão, e quem garante
-- que o código existe é o CurriculumValidator, no build.
CREATE TABLE node_position (
    node_id        BIGINT      NOT NULL REFERENCES node (id),
    position_order INT         NOT NULL,
    position_code  VARCHAR(40) NOT NULL,
    PRIMARY KEY (node_id, position_order)
);

-- Apelidos do nó ("armbar", "RNC"), para a busca do diário achar a técnica pelo nome que se ouve
-- no tatame.
CREATE TABLE node_alias (
    node_id     BIGINT      NOT NULL REFERENCES node (id),
    alias_order INT         NOT NULL,
    alias       VARCHAR(60) NOT NULL,
    PRIMARY KEY (node_id, alias_order)
);
